async def main():
    srv = subprocess.Popen([sys.executable, str(ROOT / 'server.py'), str(PORT)], env={**os.environ})
    time.sleep(0.8)
    try:
        async with async_playwright() as p:
            b = await p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1194/chrome-linux/chrome')
            page, errs = await new_page(b)
            tests = [('dc31', t31), ('dc32', t32), ('dc33', t33), ('dc34', t34), ('dc35', t35),
                     ('dc36', t36), ('dc37', t37), ('dc38', t38), ('dc39', t39), ('dc40', t40)]
            for ex, fn in tests:
                if ONLY and ex not in ONLY:
                    continue
                errs.clear()
                try:
                    await fn(page)
                except Exception as e:  # noqa: BLE001
                    check(ex + ' crashed', False, e)
                    try:
                        await close(page)
                    except Exception:  # noqa: BLE001
                        pass
                check(ex + ' no page errors', not errs, errs)
            await b.close()
    finally:
        srv.terminate()
    fails = [n for n, ok in results if not ok]
    print(f'\n{len(results) - len(fails)}/{len(results)} passed')
    if fails:
        print('FAILED:', fails)


