import asyncio, subprocess, sys, time, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from playwright.async_api import async_playwright
ROOT = pathlib.Path(__file__).parent
PORT = 8767
SHIM = open(ROOT/'run.py').read().split('SHIM = """')[1].split('"""')[0]
async def main():
    srv = subprocess.Popen([sys.executable, str(ROOT / 'server.py'), str(PORT)]); time.sleep(0.8)
    try:
        async with async_playwright() as p:
            b = await p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1194/chrome-linux/chrome')
            page = await b.new_page(viewport={'width': 1600, 'height': 950})
            errs=[]; page.on('pageerror', lambda e: errs.append(str(e)))
            async def route(r):
                u = r.request.url
                if 'react-dom' in u: await r.fulfill(body='', content_type='text/javascript')
                elif 'react' in u: await r.fulfill(path=str(ROOT / 'react-bundle.js'), content_type='text/javascript')
                elif 'babel' in u: await r.fulfill(body=SHIM, content_type='text/javascript')
                elif 'fonts.g' in u: await r.fulfill(body='', content_type='text/css')
                else: await r.continue_()
            await page.route('**/*', route)
            await page.goto(f'http://127.0.0.1:{PORT}/'); await page.wait_for_timeout(600)
            await page.evaluate('Workspace.open("m5")'); await page.wait_for_timeout(1000)
            await page.click('[data-ptab="design"]'); await page.wait_for_timeout(1800)
            await page.click('[data-dmode="interact"]')
            h = page.locator('#designHost')
            names = lambda: h.locator('tbody .cell-name').all_inner_texts()
            rev = h.locator('th .sort-btn').nth(1)
            await rev.click(); await page.wait_for_timeout(100); print('desc:', (await names())[:3], await rev.inner_text())
            await rev.click(); await page.wait_for_timeout(100); print('asc last:', (await names())[-2:], await rev.inner_text())
            await h.locator('select.select').select_option('trial'); await page.wait_for_timeout(100)
            print('trial:', await names(), await h.locator('.page-sub').inner_text())
            await h.locator('.search-input').fill('zzz'); await page.wait_for_timeout(100)
            print('empty:', await h.locator('.empty p').inner_text())
            await h.locator('.link-btn').click(); await page.wait_for_timeout(100)
            print('cleared:', await h.locator('.page-sub').inner_text())
            await h.locator('th .sort-btn').first.click(); await page.wait_for_timeout(100)
            print('name asc:', (await names())[:2], 'rev hdr:', await rev.inner_text())
            await h.locator('tbody tr').nth(2).click(); await page.wait_for_timeout(200)
            print('drawer:', (await h.locator('.drawer').inner_text()).replace(chr(10),' | ')[:160])
            await page.screenshot(path=str(ROOT/'m5-design.png'))
            await h.locator('.icon-btn').click(); await page.wait_for_timeout(100)
            print('drawer closed:', await h.locator('.drawer').count())
            await page.evaluate('Workspace.close()')
            await page.evaluate('Workspace.open("m6")'); await page.wait_for_timeout(1000)
            await page.click('[data-ptab="design"]'); await page.wait_for_timeout(1800)
            await page.click('[data-dmode="interact"]')
            h = page.locator('#designHost')
            await h.locator('.page-header .btn-primary').click(); await page.wait_for_timeout(200)
            create = h.locator('.modal .btn-primary')
            print('create disabled:', await create.is_disabled())
            focused = await page.evaluate("document.querySelector('#designHost').shadowRoot ? document.querySelector('#designHost').shadowRoot.activeElement && document.querySelector('#designHost').shadowRoot.activeElement.className : 'n/a'")
            print('focused:', focused)
            await h.locator('.modal input.input').fill('Ship it')
            await h.locator('.seg').nth(2).click()
            await page.screenshot(path=str(ROOT/'m6-design.png'))
            await h.locator('.modal input.input').press('Enter'); await page.wait_for_timeout(200)
            print('modal gone:', await h.locator('.modal').count(), '| first:', await h.locator('.task').first.inner_text(), '|', await h.locator('.page-sub').inner_text())
            await h.locator('.page-header .btn-primary').click(); await page.wait_for_timeout(200)
            print('fresh:', repr(await h.locator('.modal input.input').input_value()))
            await h.locator('.modal h2').click(); await page.wait_for_timeout(100)
            print('inside click keeps:', await h.locator('.modal').count())
            await page.keyboard.press('Escape'); await page.wait_for_timeout(200)
            print('esc closes:', await h.locator('.modal').count())
            await h.locator('.page-header .btn-primary').click(); await page.wait_for_timeout(200)
            await h.locator('.backdrop').click(position={'x': 5, 'y': 5}); await page.wait_for_timeout(200)
            print('backdrop closes:', await h.locator('.modal').count())
            print('errs', errs)
            await b.close()
    finally: srv.terminate()
asyncio.run(main())
